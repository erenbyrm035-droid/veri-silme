-- --- YEDEK ---------------------------------------------------------------
-- İsim güncellemelerinden ÖNCE mevcut durumu sakla. Geri dönüş:
--   update public.exercises e set english_name = b.english_name
--     from public.exercises_name_backup b where b.id = e.id;
create table if not exists public.exercises_name_backup (
  id           uuid,
  name         text,
  english_name text,
  backed_up_at timestamptz not null default now()
);

-- Yedek yalnızca BOŞSA doldurulur.
--   · İlk çalıştırma  → değişiklikten önceki hali kaydedilir (istenen)
--   · Tekrar çalıştırma → ilk yedek KORUNUR, üzerine yazılmaz
-- `create table if not exists ... as select` bunu yapamıyordu: tablo herhangi
-- bir sebeple önceden oluşmuşsa (ör. veri yüklenmeden önce çalıştırıldıysa)
-- yedek sonsuza kadar boş kalıyor ve UPDATE'ler yine de işliyordu.
insert into public.exercises_name_backup (id, name, english_name)
select id, name, english_name from public.exercises
where not exists (select 1 from public.exercises_name_backup);

-- --- A) WORKOUT ENGINE SÜTUNLARI ------------------------------------------
-- Şu ana kadar set satırı yalnızca "kaç tekrar, kaç kilo" tutuyordu. Motor
-- için hedef/gerçekleşen ayrımı ve efor ölçüsü gerekiyor.
alter table public.workout_sets
  add column if not exists target_reps int,               -- planlanan tekrar
  add column if not exists rir         int,               -- Reps In Reserve (0-5)
  add column if not exists rpe         numeric(3,1),      -- Rate of Perceived Exertion (1-10)
  add column if not exists rest_sec    int,               -- bu setten sonra dinlenilen süre
  add column if not exists notes       text;

-- Aralık koruması: bozuk istemci verisi ilerleme hesabını yanıltmasın.
do $$
begin
  if not exists (select 1 from pg_constraint where conname = 'workout_sets_rir_range') then
    alter table public.workout_sets add constraint workout_sets_rir_range
      check (rir is null or (rir >= 0 and rir <= 10));
  end if;
  if not exists (select 1 from pg_constraint where conname = 'workout_sets_rpe_range') then
    alter table public.workout_sets add constraint workout_sets_rpe_range
      check (rpe is null or (rpe >= 1 and rpe <= 10));
  end if;
end $$;

