-- İKİ İŞ YAPAR:
--   A) Workout Engine için eksik sütunlar (RIR/RPE/hedef tekrar/dinlenme)
--   B) `english_name` standardizasyonu + `aliases` + `video_slug`
--
-- KRİTİK: `exercises.name` sütununa DOKUNULMAZ.
--   `workout_sets.exercise_name` ve `personal_records.exercise_name` bu ismin
--   kopyasını tutuyor; PR tablosunun benzersizlik kısıtı da (unique(user_id,
--   exercise_name)) ona bağlı. `name` değişseydi tüm geçmiş antrenman ve
--   rekor kayıtları kopardı. Bu yüzden `name` iç anahtar olarak kalıyor,
--   kullanıcıya gösterilen isim `english_name` üzerinden çözülüyor.
--
-- Additive + idempotent. İki kez çalıştırılabilir.
